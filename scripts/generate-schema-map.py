#!/usr/bin/env python3
"""Write spec/19-schema-map.md: one row per database table (OFH-7).

Reads governance/personal-data-inventory.csv (a test, tests/personal_data_inventory.rs, already fails
when it disagrees with the migrated schema) and the SeaORM entity files under src/db/entities. No
database and no network, so the output is deterministic.

  python3 scripts/generate-schema-map.py           rewrite the file
  python3 scripts/generate-schema-map.py --check   exit 1 if it is stale (used by CI)
"""
import csv, pathlib, re, sys, collections

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "spec" / "19-schema-map.md"
rust = root / "patient-administration-system-with-rust"

tables = collections.OrderedDict()
with open(root / "governance" / "personal-data-inventory.csv", newline="", encoding="utf-8") as f:
    for row in csv.DictReader(f):
        t = tables.setdefault(row["table"], {"cols": 0, "personal": set(), "retention": set()})
        t["cols"] += 1
        if row["category"] != "none":
            t["personal"].add(row["category"])
        t["retention"].add(row["retention_class"])

entity = {}
for p in sorted((rust / "src" / "db" / "entities").glob("*.rs")):
    m = re.search(r'table_name\s*=\s*"([^"]+)"', p.read_text(encoding="utf-8"))
    if m:
        entity[m.group(1)] = p.name

lines = [
    "# 19. Schema map",
    "",
    "Generated by `python3 scripts/generate-schema-map.py`; do not edit. CI fails when it is stale. "
    "It lists every table in [`governance/personal-data-inventory.csv`](../governance/personal-data-inventory.csv), "
    "which a test keeps equal to the migrated schema (NFR-12), so a new table cannot be added without "
    "appearing here. The purpose, creator and states of each table are not generated: they are in the "
    "chapters named by the requirement that created it (OFH-7).",
    "",
    f"{len(tables)} tables.",
    "",
    "| Table | Columns | Personal-data categories | Retention class | Entity file |",
    "|---|---|---|---|---|",
]
for name, t in sorted(tables.items()):
    cats = ", ".join(sorted(t["personal"])) or "none"
    ent = f"`src/db/entities/{entity[name]}`" if name in entity else "none (raw SQL)"
    lines.append(f"| `{name}` | {t['cols']} | {cats} | {', '.join(sorted(t['retention']))} | {ent} |")
text = "\n".join(lines) + "\n"

if "--check" in sys.argv:
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        print("spec/19-schema-map.md is stale: run python3 scripts/generate-schema-map.py", file=sys.stderr)
        sys.exit(1)
    print("schema map is current")
else:
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out.relative_to(root)} ({len(tables)} tables)")
